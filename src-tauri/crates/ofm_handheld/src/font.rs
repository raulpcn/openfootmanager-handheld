const W: usize = 640;
const H: usize = 480;

pub fn draw_text(buf: &mut [u32], text: &str, x: i32, y: i32, color: u32, scale: usize) {
    let mut cx = x;
    for ch in text.bytes() {
        let glyph = FONT[ch as usize & 0x7F];
        for row in 0..8 {
            let bits = glyph[row];
            for col in 0..8 {
                if bits & (0x80 >> col) != 0 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = cx + col as i32 * scale as i32 + sx as i32;
                            let py = y + row as i32 * scale as i32 + sy as i32;
                            if px >= 0 && px < W as i32 && py >= 0 && py < H as i32 {
                                buf[py as usize * W + px as usize] = color;
                            }
                        }
                    }
                }
            }
        }
        cx += 8 * scale as i32;
    }
}

pub fn fill_rect(buf: &mut [u32], x: i32, y: i32, w: i32, h: i32, color: u32) {
    for dy in 0..h {
        for dx in 0..w {
            let px = x + dx;
            let py = y + dy;
            if px >= 0 && px < W as i32 && py >= 0 && py < H as i32 {
                buf[py as usize * W + px as usize] = color;
            }
        }
    }
}
